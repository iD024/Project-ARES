def compile_rover_geojson(rover_id: str, rover_name: str, milestones: list) -> dict:
    line_coordinates = [[m["lon"], m["lat"]] for m in milestones]

    features = []

    # 1. Continuous Polyline Traverse Feature
    features.append(
        {
            "type": "Feature",
            "id": f"{rover_id}-traverse-path",
            "properties": {
                "roverId": rover_id,
                "roverName": rover_name,
                "featureType": "ROVER_TRAVERSE_PATH",
                "totalDistanceKm": milestones[-1]["distanceKm"],
                "totalSols": milestones[-1]["sol"],
                "startSite": milestones[0]["siteName"],
                "latestSite": milestones[-1]["siteName"],
                "datum": "Mars 2000 Sphere / Spheroid (WKID 104971)",
                "classification": "ARCHIVED OBSERVATION (PDS)",
            },
            "geometry": {
                "type": "LineString",
                "coordinates": line_coordinates,
            },
        }
    )

    # 2. Point Sol Milestone Features
    for m in milestones:
        features.append(
            {
                "type": "Feature",
                "id": f"{rover_id}-sol-{m['sol']}",
                "properties": {
                    "roverId": rover_id,
                    "roverName": rover_name,
                    "featureType": "SOL_MILESTONE",
                    "sol": m["sol"],
                    "earthDate": m["earthDate"],
                    "elevationMeters": m["elevationMeters"],
                    "distanceKm": m["distanceKm"],
                    "siteName": m["siteName"],
                    "formation": m.get("formation", "Martian Surface Bedrock"),
                    "instrumentTargets": m.get("instrumentTargets", []),
                    "discoverySummary": m.get("discoverySummary", ""),
                    "pdsCitation": m.get("pdsCitation", "NASA Planetary Data System"),
                    "classification": "ARCHIVED OBSERVATION (PDS)",
                },
                "geometry": {
                    "type": "Point",
                    "coordinates": [m["lon"], m["lat"]],
                },
            }
        )

    return {
        "type": "FeatureCollection",
        "name": f"ARES_{rover_id.upper()}_Traverse_PDS",
        "crs": {
            "type": "name",
            "properties": {
                "name": "urn:ogc:def:crs:EPSG::104971",
            },
        },
        "features": features,
    }


